-- Healthcare Analytics Star Schema
-- Fact table: 1 row per encounter.

DROP SCHEMA IF EXISTS healthcare_analysis_data_warehouse CASCADE;
CREATE SCHEMA healthcare_analysis_data_warehouse;
SET search_path = healthcare_analysis_data_warehouse;


-- DIMENSION TABLES

-- Table for dates (years, months, days)
CREATE TABLE dim_date (
    date_key          INT          PRIMARY KEY,          
    calendar_date     DATE         NOT NULL UNIQUE,
    year              SMALLINT     NOT NULL,
    quarter           SMALLINT     NOT NULL,             
    quarter_label     CHAR(7)      NOT NULL,             
    month             SMALLINT     NOT NULL,             
    month_name        VARCHAR(10)  NOT NULL,             
    year_month        CHAR(7)      NOT NULL,             
    month_start_date  DATE         NOT NULL,
    week_of_year      SMALLINT     NOT NULL,             
    day_of_month      SMALLINT     NOT NULL,
    day_of_week       SMALLINT     NOT NULL,             
    day_name          VARCHAR(10)  NOT NULL,
    is_weekend        BOOLEAN      NOT NULL,
    fiscal_year       SMALLINT     NOT NULL,             
    fiscal_quarter    SMALLINT     NOT NULL
);
CREATE INDEX ix_dim_date_year_month ON dim_date (year, month);

-- Table for medical specialties (e.g., Cardiology)
CREATE TABLE dim_specialty (
    specialty_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specialty_id    INT          UNIQUE,
    specialty_name  VARCHAR(100) NOT NULL,
    specialty_code  VARCHAR(10)
);

-- Table for hospital departments (e.g., Emergency Room)
CREATE TABLE dim_department (
    department_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id    INT          UNIQUE,
    department_name  VARCHAR(100) NOT NULL,
    floor            INT,
    capacity         INT
);

-- Table for visit types (e.g., Inpatient, Outpatient)
CREATE TABLE dim_encounter_type (
    encounter_type_key  SMALLINT     PRIMARY KEY,
    encounter_type_name VARCHAR(50)  NOT NULL UNIQUE,
    care_setting        VARCHAR(20)  NOT NULL,           
    is_inpatient        BOOLEAN      NOT NULL
);

-- Table for patient information
CREATE TABLE dim_patient (
    patient_key    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id     INT          UNIQUE,
    mrn            VARCHAR(20),
    first_name     VARCHAR(100),
    last_name      VARCHAR(100),
    full_name      VARCHAR(201),
    gender         CHAR(1),
    date_of_birth  DATE,
    age_group      VARCHAR(10),                          
    row_hash       CHAR(32),                             
    updated_at     TIMESTAMP    NOT NULL DEFAULT now()
);

-- Provider dimension, SCD Type 2: one row per provider VERSION.
-- effective_from/to + is_current keep history when a provider changes specialty.
CREATE TABLE dim_provider (
    provider_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id       INT,
    first_name        VARCHAR(100),
    last_name         VARCHAR(100),
    full_name         VARCHAR(201),
    credential        VARCHAR(20),
    specialty_key     INT          REFERENCES dim_specialty(specialty_key),
    specialty_name    VARCHAR(100),
    department_key    INT          REFERENCES dim_department(department_key),
    department_name   VARCHAR(100),
    row_hash          CHAR(32),
    effective_from    DATE         NOT NULL,
    effective_to      DATE         NOT NULL DEFAULT DATE '9999-12-31',
    is_current        BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE UNIQUE INDEX ux_dim_provider_current ON dim_provider (provider_id) WHERE is_current;
CREATE INDEX ix_dim_provider_lookup ON dim_provider (provider_id, effective_from, effective_to);

-- Table for illness codes (ICD-10)
CREATE TABLE dim_diagnosis (
    diagnosis_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnosis_id       INT          UNIQUE,
    icd10_code         VARCHAR(10)  NOT NULL,
    icd10_description  VARCHAR(200),
    icd10_chapter      CHAR(1)                           
);

-- Table for medical actions/procedures (CPT)
CREATE TABLE dim_procedure (
    procedure_key    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id     INT          UNIQUE,
    cpt_code         VARCHAR(10)  NOT NULL,
    cpt_description  VARCHAR(200)
);


-- FACT TABLE

-- Fact table: grain = ONE ROW PER ENCOUNTER.
-- Billing, diagnosis/procedure counts and readmission flags are pre-calculated here.
CREATE TABLE fact_encounters (
    encounter_key           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id            INT          NOT NULL UNIQUE,         

    -- Links to the dimension tables
    encounter_date_key      INT          NOT NULL REFERENCES dim_date(date_key),
    discharge_date_key      INT          NOT NULL REFERENCES dim_date(date_key),
    claim_date_key          INT          NOT NULL REFERENCES dim_date(date_key), 
    patient_key             INT          NOT NULL REFERENCES dim_patient(patient_key),
    provider_key            INT          NOT NULL REFERENCES dim_provider(provider_key),
    specialty_key           INT          NOT NULL REFERENCES dim_specialty(specialty_key),       
    department_key          INT          NOT NULL REFERENCES dim_department(department_key),
    encounter_type_key      SMALLINT     NOT NULL REFERENCES dim_encounter_type(encounter_type_key),
    primary_diagnosis_key   INT          NOT NULL REFERENCES dim_diagnosis(diagnosis_key),       

    -- Timestamps
    encounter_ts            TIMESTAMP    NOT NULL, 
    discharge_ts            TIMESTAMP,

    -- Pre-calculated numbers to make reports faster
    patient_age_at_encounter SMALLINT,
    length_of_stay_hours    NUMERIC(8,2),
    length_of_stay_days     SMALLINT,                             
    diagnosis_count         SMALLINT     NOT NULL DEFAULT 0,
    procedure_count         SMALLINT     NOT NULL DEFAULT 0,
    claim_count             SMALLINT     NOT NULL DEFAULT 0,
    total_claim_amount      NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_allowed_amount    NUMERIC(14,2) NOT NULL DEFAULT 0,
    
    -- Pre-calculated readmission flags
    is_index_inpatient_stay BOOLEAN      NOT NULL DEFAULT FALSE,  
    is_readmitted_30d       BOOLEAN      NOT NULL DEFAULT FALSE,  
    days_to_next_admission  INT,                                  

    etl_batch_id            BIGINT,
    loaded_at               TIMESTAMP    NOT NULL DEFAULT now()
);

-- Basic indexes for foreign keys
CREATE INDEX ix_fe_patient        ON fact_encounters (patient_key);
CREATE INDEX ix_fe_provider       ON fact_encounters (provider_key);

-- Helps monthly reporting run faster (Q1)
CREATE INDEX ix_fe_date_spec_type ON fact_encounters
       (encounter_date_key, specialty_key, encounter_type_key) INCLUDE (patient_key);

-- Helps revenue reporting run faster (Q4)
CREATE INDEX ix_fe_claim_spec_amt ON fact_encounters 
       (claim_date_key, specialty_key) INCLUDE (total_allowed_amount, claim_count);
       
-- Helps readmission reports run faster (Q3)
CREATE INDEX ix_fe_index_stays    ON fact_encounters (specialty_key)
       INCLUDE (is_readmitted_30d) WHERE is_index_inpatient_stay;      


-- BRIDGE TABLES

-- Connects visits to illnesses
CREATE TABLE bridge_encounter_diagnoses (
    encounter_key       BIGINT    NOT NULL REFERENCES fact_encounters(encounter_key),
    diagnosis_key       INT       NOT NULL REFERENCES dim_diagnosis(diagnosis_key),
    diagnosis_sequence  SMALLINT  NOT NULL,
    is_primary          BOOLEAN   NOT NULL,
    PRIMARY KEY (encounter_key, diagnosis_key)
);
CREATE INDEX ix_bed_diagnosis ON bridge_encounter_diagnoses (diagnosis_key, encounter_key);

-- Connects visits to procedures
CREATE TABLE bridge_encounter_procedures (
    encounter_key       BIGINT    NOT NULL REFERENCES fact_encounters(encounter_key),
    procedure_key       INT       NOT NULL REFERENCES dim_procedure(procedure_key),
    first_procedure_date_key INT  NOT NULL REFERENCES dim_date(date_key),
    quantity            SMALLINT  NOT NULL DEFAULT 1,
    PRIMARY KEY (encounter_key, procedure_key)
);
CREATE INDEX ix_bep_procedure ON bridge_encounter_procedures (procedure_key, encounter_key);


-- SUMMARY TABLE

-- Saves a pre-calculated list of top illness+procedure combinations
CREATE TABLE agg_dx_px_pair (
    diagnosis_key        INT     NOT NULL REFERENCES dim_diagnosis(diagnosis_key),
    procedure_key        INT     NOT NULL REFERENCES dim_procedure(procedure_key),
    encounter_count      INT     NOT NULL,
    first_date_key       INT     NOT NULL,
    last_date_key        INT     NOT NULL,
    PRIMARY KEY (diagnosis_key, procedure_key)
);
CREATE INDEX ix_agg_pair_count ON agg_dx_px_pair (encounter_count DESC);



